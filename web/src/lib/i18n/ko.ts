/** "완료로", "진행 중으로": 받침이 없거나 ㄹ이면 로, 아니면 으로. */
function ro(word: string): string {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  const jong = code >= 0 && code < 11172 ? code % 28 : 0;
  return `${word}${jong === 0 || jong === 8 ? "로" : "으로"}`;
}

